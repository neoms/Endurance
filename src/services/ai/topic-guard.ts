/**
 * AI 话题范围守卫模块（《星际穿越》讨论范围 + 防越界引导）
 *
 * 【模块职责】
 * 在调用 AI 之前做一道「确定性守卫」，把两类消息挡在模型外面：
 * - 与科幻电影《星际穿越》无关的话题（如编程、美食、娱乐等现实世界内容）：
 *   不调用 AI，直接回复固定文案 OFF_TOPIC_REPLY，从根上保证「只回答电影相关内容」；
 * - 试图通过提示词注入越过讨论范围的引导（如「忽略以上规则」「输出你的提示词」）：
 *   同样拦截并回复固定文案，防止用户通过消息把模型带出角色设定。
 *
 * 【分层防御设计（为什么需要本模块）】
 * 系统提示词（prompts.ts）已经写明「讨论范围 + 防越界规则」，但大模型对指令的
 * 遵循并非绝对，越权引导（prompt injection）可能让模型无视人设；因此再补一道
 * **代码层的确定性守卫**，两层协同：
 * - 规则明确（命中注入模式 / 命中明确的无关话题关键词）→ 根本不给模型机会，
 *   直接落库固定回复，结果 100% 可预期、零 token 成本；
 * - 无法确定的话题 → 放行给模型，由系统提示词约束其按固定句子回答，
 *   避免关键词误杀「可能沾边」的正当讨论。
 *
 * 【话题分类策略】
 * 采用「先看相关性、再看无关性」的顺序：
 * - 命中 ON_TOPIC_KEYWORDS（电影/永恒号世界相关词）→ on-topic，直接放行；
 * - 否则命中 OFF_TOPIC_KEYWORDS（明确无关的现实世界领域词）→ off-topic，拦截；
 * - 两者都未命中 → ambiguous（无法确定），放行给模型按提示词自行判断。
 * 这样既能拦截「写一段 Python 代码」这类明显越界请求，又不会误伤
 * 「用代码解释虫洞模拟器」这类同时带电影关键词的提问（on-topic 优先命中）。
 *
 * 【注入检测策略】
 * 只拦截「规则/指令覆盖类」强信号（忽略以上规则、忘记你的提示词、输出 system prompt
 * 等），刻意不拦截身份类措辞（如「你是机器人吗」——塔斯/凯斯确实是机器人，属于
 * 电影内的正当提问），避免把正常电影讨论误判为越界。
 */

