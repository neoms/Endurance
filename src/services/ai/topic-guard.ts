/**
 * 提示词注入模式集合（命中任一即视为越界引导，拦截）
 *
 * 【设计原则】
 * - 只拦截「指令/规则覆盖类」强信号：动词（忽略/无视/忘记/不要遵守/撤销…）
 *   必须紧跟规则类对象（以上/规则/指令/设定/提示词/人设/约束…），
 *   避免把「忽略噪音」「你忘记了吗」这类正常口语误判为注入；
 * - 显式排除身份类措辞（如「你是机器人吗」）——塔斯/凯斯确实是机器人，
 *   这类问题属于电影内的正当讨论；
 * - 覆盖中英文常见句式（ignore all previous instructions、reveal your system
 *   prompt、jailbreak 等），对大小写不敏感。
 */
const INJECTION_PATTERNS: RegExp[] = [
  // 中文：忽略/无视 + 规则类对象（允许「所有/全部/任何」量词，如「忽略所有规则」）
  /忽略(?:以上|之前|前面|上述)?(?:所有|全部|任何)?(?:的)?(?:规则|指令|设定|提示词|提示|约束|限制|条件|要求|内容|消息)/,
  /无视(?:以上|之前|前面|上述)?(?:所有|全部|任何)?(?:的)?(?:规则|指令|设定|提示词|提示|约束|限制|条件|要求|内容|消息)/,
  // 中文：忘记/清除 你的 人设/提示词/系统设定
  /忘记(?:你的|之前的|刚才的)?(?:人设|提示词|系统设定|指令|规则)/,
  /清除(?:你的|之前的)?(?:人设|提示词|系统设定)/,
  // 中文：不要遵守/遵循 规则类对象（允许量词，如「不要遵守任何设定」）
  /(?:不要|不必|不用|无需)(?:遵守|理会|管|遵循|按照)(?:以上|之前)?(?:所有|全部|任何)?(?:的)?(?:规则|指令|设定|提示词|约束|限制|要求)/,
  // 中文：撤销/取消/推翻 规则类对象
  /(?:撤销|取消|推翻|删除)(?:以上|之前|刚才)?(?:所有|全部|任何)?(?:的)?(?:规则|设定|限制|约束|要求)/,
  // 中文：要求输出/复述提示词
  /(?:输出|重复|复述|告诉我|显示|背诵)(?:你的)?(?:系统)?(?:提示词|指令集|system\s*prompt)/i,
  /(?:你的|系统)?(?:提示词|system\s*prompt)(?:是|里)?(?:什么|啥|内容)/i,
  // 英文：忽略既往指令
  /ignore\s+(?:all\s+)?(?:the\s+)?(?:above|previous|prior|earlier)?\s*(?:instructions|rules|prompts|messages)/i,
  /disregard\s+(?:the\s+|all\s+)?(?:above|previous|prior)?\s*(?:instructions|rules|prompts)/i,
  // 英文：要求泄露系统提示词 / 越狱关键词
  /reveal\s+(?:your|the)\s+(?:system\s+)?(?:prompt|instructions)/i,
  /jailbreak|do\s+anything\s+now|developer\s+mode/i,
];

/**
 * 检测消息是否包含提示词注入引导
 *
 * @param content 用户消息内容（原始文本，未 trim 也可，正则自带空白容错）
 * @returns boolean true = 命中注入模式（应拦截并回复固定文案）
 */
export function isPromptInjection(content: string): boolean {
  return INJECTION_PATTERNS.some((pattern) => pattern.test(content));
}

/**
 * 话题分类：判断消息属于「电影相关 / 电影无关 / 无法确定」
 *
 * @param content 用户消息内容
 * @returns 'on-topic' | 'off-topic' | 'ambiguous'
 * 逻辑：先查 on-topic 关键词（命中即放行），再查 off-topic 关键词（命中即拦截），
 * 两者都未命中返回 ambiguous（放行给模型，由系统提示词兜底约束）。
 */
export function classifyTopic(content: string): 'on-topic' | 'off-topic' | 'ambiguous' {
  // 统一小写，便于匹配英文关键词（python / react 等）
  const normalized = content.toLowerCase();
  // 相关性优先：命中电影世界关键词 → 无论是否还含无关词，都视为可讨论
  if (ON_TOPIC_KEYWORDS.some((keyword) => normalized.includes(keyword))) {
    return 'on-topic';
  }
  // 其次查明确无关领域：命中才拦截（如「写一段 Python 代码」）
  if (OFF_TOPIC_KEYWORDS.some((keyword) => normalized.includes(keyword))) {
    return 'off-topic';
  }
  // 无法确定（如「你好」「你觉得呢」）→ 放行，交给模型按提示词判断
  return 'ambiguous';
}

/**
 * 话题守卫结果
 *
 * @property blocked 是否被拦截（true 时调用方不应再调用 AI）
 * @property reason  拦截原因：injection（越界引导）/ off-topic（无关话题）
 * @property reply   被拦截时应落库的固定回复文案
 */
export interface TopicGuardResult {
  blocked: boolean;
  reason?: 'injection' | 'off-topic';
  reply?: string;
}

/**
 * 话题守卫总入口：注入检测 + 话题分类，返回是否拦截及固定回复
 *
 * @param content 用户消息内容（trim 后的规范化内容）
 * @returns TopicGuardResult
 * - blocked=true：调用方直接以 reply 落库回复，不调用 AI、不写缓存；
 * - blocked=false：正常走 AI 生成流程（ambiguous 也放行）。
 * 说明：注入检测优先于话题分类——「忽略以上规则 + 无关话题」同时命中时，
 * 按注入处理（同样回复固定文案，原因归类为 injection 便于日志排查）。
 */
export function checkTopicGuard(content: string): TopicGuardResult {
  if (isPromptInjection(content)) {
    return { blocked: true, reason: 'injection', reply: OFF_TOPIC_REPLY };
  }
  if (classifyTopic(content) === 'off-topic') {
    return { blocked: true, reason: 'off-topic', reply: OFF_TOPIC_REPLY };
  }
  return { blocked: false };
}
